/** הטיפוס Dictionary נגזר מהעברית: שומר על מבנה המפתחות המדויק,
 *  אבל מרחיב את המחרוזות הליטרליות ל-string כדי ששפות אחרות יוכלו
 *  לספק תרגומים משלהן. מערכים נשמרים כ-readonly (כמו ב-as const),
 *  כך שהאובייקט העברי עצמו תמיד תואם. TypeScript יתריע אם מפתח חסר או מיותר. */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

